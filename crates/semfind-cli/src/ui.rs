use semfind_core::{Category, Language};

pub(crate) struct Messages {
    pub about: &'static str,
    pub init: &'static str,
    pub index: &'static str,
    pub status: &'static str,
    pub unindex: &'static str,
    pub search: &'static str,
    pub query: &'static str,
    pub kind: &'static str,
    pub distro: &'static str,
    pub exclude: &'static str,
    pub clear_excludes: &'static str,
    pub manpages: &'static str,
    pub caption_images: &'static str,
    pub no_caption_images: &'static str,
    pub json: &'static str,
    pub category: &'static str,
    pub path: &'static str,
    pub extension: &'static str,
    pub limit: &'static str,
    pub time: &'static str,
    pub stdin: &'static str,
    pub search_time: &'static str,
    pub hint: [&'static str; 2],
    pub status_labels: [&'static str; 6],
    pub report_labels: [&'static str; 4],
    pub init_progress: [&'static str; 6],
    pub category_labels: [&'static str; 5],
    pub root_removed: &'static str,
    pub root_missing: &'static str,
    pub home_required: &'static str,
    pub data_dir_missing: &'static str,
    pub open_index: &'static str,
    pub query_required: &'static str,
    pub command_required: &'static str,
    pub help_headers: [&'static str; 7],
}

impl Messages {
    pub fn for_language(language: Language) -> &'static Self {
        match language {
            Language::En => &EN,
            Language::De => &DE,
            Language::Ru => &RU,
            Language::Pt => &PT,
            Language::Fr => &FR,
            Language::Es => &ES,
            Language::It => &IT,
        }
    }

    pub fn category(&self, category: Category) -> &'static str {
        let [file, application, setting, command, action] = self.category_labels;
        match category {
            Category::File => file,
            Category::Application => application,
            Category::Setting => setting,
            Category::Command => command,
            Category::Action => action,
        }
    }
}

