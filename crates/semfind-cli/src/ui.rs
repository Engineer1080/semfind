impl Messages {
    pub fn for_language(language: Language) -> &'static Self {
        match language {
            Language::En => &EN,
            Language::De => &DE,
            Language::Ru => &RU,
            Language::Pt => &PT,
            Language::Fr => &FR,
            Language::Es => &ES,
            Language::It => &IT,
            Language::Zh => &zh::MESSAGES,
            Language::Ja => &ja::MESSAGES,
            Language::Nl => &nl::MESSAGES,
            Language::Pl => &pl::MESSAGES,
            Language::Tr => &tr::MESSAGES,
        }
    }

    pub fn category(&self, category: Category) -> &'static str {
        let [file, application, setting, command, action] = self.category_labels;
        match category {
            Category::File => file,
            Category::Application => application,
            Category::Setting => setting,
            Category::Command => command,
            Category::Action => action,
        }
    }
}

